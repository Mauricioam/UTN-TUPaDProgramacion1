


def calcular_area_circulo(radio):
        square_radio = radio ** 2 ## arreglo del cuadrado que faltaba
        result = round(3.14 * square_radio,2)
        return result

def calcular_perimetro_circulo(radio):
        result = round(2 * 3.14 * radio,2)
        return result

